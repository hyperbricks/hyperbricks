func TestImageOutputRootKeepsSourcesAndPublicURLs(t *testing.T) {
	dev, _, dest := cachedImageFixture(t)
	sourceStatic := filepath.Dir(dest)
	src := filepath.Join(sourceStatic, "authored", "photo.png")
	writeTestImage(t, src, color.RGBA{R: 200, A: 255})
	cfg := SingleImageConfig{Src: src, Width: 4, Cache: true}
	name := imageGenerate(t, dev, src, dest, cfg)
	devOutput := filepath.Join(dest, name)
	devInfo, devBytes := imageInfo(t, devOutput), esbuildRead(t, devOutput)
	sourceBytes := esbuildRead(t, src)
	devStore, err := dev.storeFor(dest)
	if err != nil {
		t.Fatal(err)
	}
	history := esbuildRead(t, devStore.historyPath)
	if err := dev.BeginAssetSession(dest); err != nil {
		t.Fatal(err)
	}
	exporter := NewImageProcessor()
	exporter.cacheDir = dev.cacheDir
	exporter.ownershipDir = dev.ownershipDir
	t.Cleanup(exporter.CloseAssets)
	outputStatic := filepath.Join(t.TempDir(), "rendered", "static")
	if err := exporter.SetOutputRoot(sourceStatic, outputStatic); err != nil {
		t.Fatal(err)
	}
	if err := CopyStaticAssets(context.Background(), sourceStatic, outputStatic); err != nil {
		t.Fatal(err)
	}
	if err := exporter.BeginAssetSession(dest); err != nil {
		t.Fatalf("export acquired development image session: %v", err)
	}
	markup, err := exporter.ProcessSingleImage(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if got := parsedImageAttributes(t, markup)["src"]; got != "/static/images/"+name {
		t.Fatalf("export changed public URL: %s", got)
	}
	exported := filepath.Join(outputStatic, "images", name)
	if esbuildRead(t, exported) != devBytes {
		t.Fatal("remapped image changed generated bytes")
	}
	store, err := exporter.storeFor(dest)
	if err != nil {
		t.Fatal(err)
	}
	canonical, err := esbuildExistingPath(outputStatic)
	if err != nil {
		t.Fatal(err)
	}
	if store.root != filepath.Join(canonical, "images") || store.treeRoot != canonical {
		t.Fatalf("image store and tree lock disagree with export root: %+v", store)
	}
	gallery := filepath.Join(sourceStatic, "gallery")
	writeTestImage(t, filepath.Join(gallery, "other.png"), color.RGBA{B: 200, A: 255})
	writeTestImage(t, filepath.Join(outputStatic, "gallery", "other.png"), color.RGBA{B: 200, A: 255})
	markup, err = exporter.ProcessMultipleImages(MultipleImagesConfig{Directory: gallery, Width: 4, Cache: true})
	if err != nil {
		t.Fatal(err)
	}
	galleryURL := parsedImageAttributes(t, markup)["src"]
	imageInfo(t, filepath.Join(outputStatic, strings.TrimPrefix(galleryURL, "/static/")))
	if _, err := os.Stat(filepath.Join(sourceStatic, strings.TrimPrefix(galleryURL, "/static/"))); !os.IsNotExist(err) {
		t.Fatal("export gallery wrote a development asset", err)
	}
	if esbuildRead(t, src) != sourceBytes || esbuildRead(t, devOutput) != devBytes || !os.SameFile(devInfo, imageInfo(t, devOutput)) || esbuildRead(t, devStore.historyPath) != history {
		t.Fatal("export changed authored input, development output or ownership")
	}
}

func TestImageExportReadsCurrentCopiedInputsAndGallery(t *testing.T) {
	dev, outside, dest := cachedImageFixture(t)
	static := filepath.Dir(dest)
	src := filepath.Join(static, "authored", "photo.png")
	gallery := filepath.Join(static, "gallery")
	for _, path := range []string{src, filepath.Join(gallery, "old.png"), filepath.Join(gallery, "shared.png")} {
		writeTestImage(t, path, color.RGBA{R: 200, A: 255})
	}
	cfg := SingleImageConfig{Src: src, Width: 4, Cache: true}
	oldName := imageGenerate(t, dev, src, dest, cfg)
	oldSource := esbuildRead(t, src)
	exporter := NewImageProcessor()
	exporter.cacheDir, exporter.ownershipDir = dev.cacheDir, dev.ownershipDir
	output := filepath.Join(t.TempDir(), "static")
	if err := exporter.SetOutputRoot(static, output); err != nil {
		t.Fatal(err)
	}
	if err := CopyStaticAssets(context.Background(), static, output); err != nil {
		t.Fatal(err)
	}
	// An earlier export component has refreshed static inputs in this output.
	exportedSource := filepath.Join(output, "authored", "photo.png")
	writeTestImage(t, exportedSource, color.RGBA{B: 200, A: 255})
	writeTestImage(t, filepath.Join(output, "gallery", "shared.png"), color.RGBA{B: 200, A: 255})
	writeTestImage(t, filepath.Join(output, "gallery", "new.png"), color.RGBA{B: 200, A: 255})
	if err := os.Remove(filepath.Join(output, "gallery", "old.png")); err != nil {
		t.Fatal(err)
	}
	markup, err := exporter.ProcessSingleImage(cfg)
	if err != nil {
		t.Fatal(err)
	}
	url := parsedImageAttributes(t, markup)["src"]
	if !strings.HasPrefix(url, "/static/images/photo_") || filepath.Base(url) == oldName {
		t.Fatalf("export reused development input or changed public naming: %s", url)
	}
	assertExportImageColor(t, filepath.Join(output, "images", filepath.Base(url)), true)
	multiple := MultipleImagesConfig{Directory: gallery, Width: 4, Cache: true}
	markup, err = exporter.ProcessMultipleImages(multiple)
	if err != nil || strings.Count(markup, "<img ") != 2 || strings.Contains(markup, "old_") {
		t.Fatalf("gallery used development file set: %s (%v)", markup, err)
	}
	active, err := exporter.DiscoverImages(&cfg, &multiple)
	if err != nil {
		t.Fatal(err)
	}
	if len(active) != 3 {
		t.Fatalf("discovery used development file set: %v", active)
	}
	group, _ := imageGroup(gallery, 4, 0, 0, true)
	for _, file := range []string{"new.png", "shared.png"} {
		id, _ := imageOwner(filepath.Join(gallery, file), 4, 0, 0)
		if _, exists := active[group+":"+id]; !exists {
			t.Fatalf("discovery changed authored gallery identity: %s", file)
		}
	}
	store, err := exporter.storeFor(dest)
	if err != nil {
		t.Fatal(err)
	}
	singleGroup, _ := imageGroup(src, 4, 0, 0, false)
	singleOwner, _ := imageOwner(src, 4, 0, 0)
	if store.history.Owners[singleGroup+":"+singleOwner] == nil {
		t.Fatal("export changed the authored single-image owner")
	}
	for _, owner := range store.history.Owners {
		for _, generation := range owner.Generations {
			assertExportImageColor(t, filepath.Join(store.root, generation.Name), true)
		}
	}
	// Resources outside static retain their original source semantics.
	outsideName := imageGenerate(t, exporter, outside, dest, SingleImageConfig{Width: 4, Cache: true})
	assertExportImageColor(t, filepath.Join(store.root, outsideName), false)
	if esbuildRead(t, src) != oldSource {
		t.Fatal("export changed development source")
	}
	imageInfo(t, filepath.Join(gallery, "old.png"))
	if _, err := os.Stat(filepath.Join(gallery, "new.png")); !os.IsNotExist(err) {
		t.Fatal("export changed development gallery")
	}
	if err := os.Remove(exportedSource); err != nil {
		t.Fatal(err)
	}
	if _, err := exporter.ProcessSingleImage(cfg); err == nil {
		t.Fatal("missing export input silently fell back to development bytes")
	}
}

func assertExportImageColor(t *testing.T, path string, blue bool) {
	t.Helper()
	file, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer file.Close()
	decoded, _, err := image.Decode(file)
	if err != nil {
		t.Fatal(err)
	}
	r, _, b, _ := decoded.At(0, 0).RGBA()
	if (blue && b <= r) || (!blue && r <= b) {
		t.Fatalf("wrong source pixels in %s: red=%d blue=%d", path, r, b)
	}
}

func TestImageFreshExportDoesNotAdoptCopiedOutput(t *testing.T) {
	previous, src, dest := cachedImageFixture(t)
	sourceStatic := filepath.Dir(dest)
	outputStatic := filepath.Join(t.TempDir(), "rendered", "static")
	if err := previous.SetOutputRoot(sourceStatic, outputStatic); err != nil {
		t.Fatal(err)
	}
	name := imageGenerate(t, previous, src, dest, SingleImageConfig{Width: 4, Cache: true, CacheGrace: "0s"})
	store, err := previous.storeFor(dest)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(store.root, name)
	contents := esbuildRead(t, path)
	unrelated := filepath.Join(previous.cacheDir, "other-root.json")
	esbuildWrite(t, unrelated, "other root ownership")
	previous.CloseAssets()
	if err := os.RemoveAll(outputStatic); err != nil {
		t.Fatal(err)
	}
	esbuildWrite(t, path, contents)
	fresh := NewImageProcessor()
	fresh.cacheDir = previous.cacheDir
	fresh.ownershipDir = previous.ownershipDir
	t.Cleanup(fresh.CloseAssets)
	if err := fresh.SetOutputRoot(sourceStatic, outputStatic); err != nil {
		t.Fatal(err)
	}
	if err := fresh.BeginAssetSession(dest); err != nil {
		t.Fatal(err)
	}
	if err := fresh.ResetAssetsForFreshExport(context.Background(), filepath.Join(outputStatic, "images")); err != nil {
		t.Fatal(err)
	}
	if err := fresh.ReconcileAssets(dest, map[string]ImageAssetPolicy{}); err != nil {
		t.Fatal(err)
	}
	if esbuildRead(t, path) != contents || fresh.OwnsOutput(path) {
		t.Fatal("fresh export adopted or changed copied input")
	}
	if esbuildRead(t, unrelated) != "other root ownership" {
		t.Fatal("fresh export changed another root's ownership")
	}
	if _, err := os.Stat(store.historyPath); !os.IsNotExist(err) {
		t.Fatal("fresh export preserved previous ownership history", err)
	}
	other := NewImageProcessor()
	other.cacheDir = t.TempDir()
	other.ownershipDir = other.cacheDir
	t.Cleanup(other.CloseAssets)
	if err := other.BeginAssetSession(filepath.Join(outputStatic, "images")); err == nil {
		t.Fatal("fresh export reset released its image session")
	}
}

func TestImagePublicationWaitsForStaticCopyAndCancels(t *testing.T) {
	p, src, dest := cachedImageFixture(t)
	cfg := SingleImageConfig{Width: 4, Cache: true, CacheGrace: "0s"}
	old := imageGenerate(t, p, src, dest, cfg)
	store, err := p.storeFor(dest)
	if err != nil {
		t.Fatal(err)
	}
	history := esbuildRead(t, store.historyPath)
	writeTestImage(t, src, color.RGBA{B: 200, A: 255})
	unlock, err := LockAssetTree(context.Background(), filepath.Dir(dest), true)
	if err != nil {
		t.Fatal(err)
	}
	defer func() {
		if unlock != nil {
			unlock()
		}
	}()
	ctx, cancel := context.WithTimeout(context.Background(), 500*time.Millisecond)
	defer cancel()
	cfg.renderContext = ctx
	if _, err := p.processImage(src, dest, cfg); !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("image publication ignored static copy or cancellation: %v", err)
	}
	entries, err := os.ReadDir(dest)
	if err != nil || len(entries) != 1 || entries[0].Name() != old || esbuildRead(t, store.historyPath) != history {
		t.Fatal("blocked image publication changed assets or ownership", err)
	}
	unlock()
	unlock = nil
	cfg.renderContext = nil
	if imageGenerate(t, p, src, dest, cfg) == old {
		t.Fatal("image publication did not recover after static copy")
	}
}

func TestImageOutputRootRejectsUnsafeBindings(t *testing.T) {
	p, _, dest := cachedImageFixture(t)
	sourceStatic := filepath.Dir(dest)
	if err := p.SetOutputRoot(sourceStatic, filepath.Join(sourceStatic, "export")); err == nil {
		t.Fatal("overlapping source and output roots accepted")
	}
	if err := p.SetOutputRoot(sourceStatic, ""); err == nil {
		t.Fatal("empty output root accepted")
	}
	outputStatic := filepath.Join(t.TempDir(), "static")
	if err := p.SetOutputRoot(sourceStatic, outputStatic); err != nil {
		t.Fatal(err)
	}
	if _, err := p.storeFor(filepath.Join(t.TempDir(), "outside")); err == nil {
		t.Fatal("destination outside bound roots accepted")
	}
	if _, err := p.storeFor(dest); err != nil {
		t.Fatal(err)
	}
	if err := p.SetOutputRoot(sourceStatic, filepath.Join(t.TempDir(), "different")); err == nil {
		t.Fatal("output root changed after asset preparation")
	}
	if err := p.SetOutputRoot(sourceStatic, outputStatic); err != nil {
		t.Fatal("identical output binding was rejected", err)
	}
	plain := NewImageProcessor()
	if err := plain.ResetAssetsForFreshExport(context.Background(), dest); err == nil {
		t.Fatal("normal runtime ownership was reset as an export")
	}
}
